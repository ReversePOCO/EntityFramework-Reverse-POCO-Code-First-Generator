using System.Linq;
using System.Text.RegularExpressions;
using Efrpg;
using Generator.Tests.Common;
using Generator.Tests.Unit.DocSamples;
using NUnit.Framework;

namespace Generator.Tests.Unit
{
    /// <summary>
    ///     Settings.EnumsFileName writes every enum to one file instead of one file per enum, when generating separate
    ///     files (#770).
    /// </summary>
    [TestFixture]
    [Category(Constants.CI)]
    public class EnumsFileNameTests
    {
        private StaticStateSnapshot _snapshot;

        [OneTimeSetUp]
        public void CaptureStaticState()
        {
            _snapshot = StaticStateSnapshot.Capture();
            DocSampleRunner.Pristine = _snapshot;
        }

        [OneTimeTearDown]
        public void RestoreStaticState()
        {
            _snapshot.Restore();
        }

        [Test]
        public void GenerateCode_EnumsFileNameEmpty_WritesEachEnumToItsOwnFile()
        {
            var files = Listing(() => { });

            Assert.That(files, Is.SupersetOf(new[] { "OrderStatus.cs", "ShippingMethod.cs" }));
        }

        [Test]
        public void GenerateCode_EnumsFileNameSet_WritesNoFilePerEnum()
        {
            var files = Listing(() => Settings.EnumsFileName = "Enums");

            Assert.That(files, Has.None.EqualTo("OrderStatus.cs").And.None.EqualTo("ShippingMethod.cs"));
        }

        [Test]
        public void GenerateCode_EnumsFileNameSet_WritesEveryEnumToThatFile()
        {
            var file = DocSampleRunner.GenerateSeparateFile(() => Settings.EnumsFileName = "Enums", DocSampleRunner.Enums(), "Enums.cs");

            Assert.That(file, Does.Contain("public enum OrderStatus").And.Contain("public enum ShippingMethod"));
        }

        [Test]
        public void GenerateCode_EnumsFileNameSet_WritesTheHeaderAndNamespaceOnce()
        {
            var file = DocSampleRunner.GenerateSeparateFile(() => Settings.EnumsFileName = "Enums", DocSampleRunner.Enums(), "Enums.cs");

            Assert.That(new[] { Count(file, "<auto-generated>"), Count(file, @"^namespace ") }, Is.EqualTo(new[] { 1, 1 }));
        }

        [Test]
        public void GenerateCode_EnumsFileNameEndsInCs_DoesNotDoubleTheExtension()
        {
            var files = Listing(() => Settings.EnumsFileName = "Enums.cs");

            Assert.That(files, Has.One.EqualTo("Enums.cs").And.None.EqualTo("Enums.cs.cs"));
        }

        [Test]
        public void GenerateCode_EnumsFileNameSet_PutsTheFileWhereThePerEnumFilesWent()
        {
            var files = Listing(() =>
            {
                Settings.PocoFolder    = "Entities";
                Settings.EnumsFileName = "Enums";
            });

            Assert.That(files, Has.One.EqualTo("Entities/Enums.cs"));
        }

        [Test]
        public void GenerateCode_EnumsFileNameSetWithGeneratedCodeAttribute_EveryEnumCarriesIt()
        {
            var file = DocSampleRunner.GenerateSeparateFile(() =>
            {
                Settings.EnumsFileName                 = "Enums";
                Settings.IncludeCodeGeneratedAttribute = true;
            }, DocSampleRunner.Enums(), "Enums.cs");

            Assert.That(Count(file, @"\[GeneratedCode\("), Is.EqualTo(2));
        }

        [Test]
        public void GenerateCode_EnumsFileNameSetButNoEnums_WritesNoFile()
        {
            var files = DocSampleRunner.GenerateFileListing(() => Settings.EnumsFileName = "Enums").Split('\n');

            Assert.That(files, Has.None.EqualTo("Enums.cs"));
        }

        [Test]
        public void GenerateCode_EnumsFileNameSetWithoutSeparateFiles_ChangesNothing()
        {
            var standard = DocSampleRunner.Generate(() => { }, DocSampleRunner.Enums());
            Assert.That(standard, Does.Contain("public enum OrderStatus"), "No enums were generated, so the comparison below would pass vacuously");

            var withSetting = DocSampleRunner.Generate(() => Settings.EnumsFileName = "Enums", DocSampleRunner.Enums());

            Assert.That(withSetting, Is.EqualTo(standard));
        }

        private static string[] Listing(System.Action configure)
        {
            return DocSampleRunner.GenerateFileListing(configure, DocSampleRunner.Enums()).Split('\n');
        }

        private static int Count(string text, string pattern)
        {
            return Regex.Matches(text, pattern, RegexOptions.Multiline).Cast<Match>().Count();
        }
    }
}
